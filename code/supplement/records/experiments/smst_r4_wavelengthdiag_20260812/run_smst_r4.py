#!/usr/bin/env python3
"""SMST-R4: locked real paired-instrument experiment.

The three stages intentionally separate development, validation, and final
evaluation.  No stage modifies the immutable inputs.  The final stage requires
the validation decision lock generated by a prior stage.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import pickle
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, f1_score
from sklearn.preprocessing import StandardScaler


SEED_TEXT = "smst-r4-20260812:"
GLOBAL_GRID = (1e-6, 1e-4, 1e-2, 1.0)
DECODER_GRID = (1e-5, 1e-3, 1e-1)
RESIDUAL_GRID = (1e-6, 1e-4, 1e-2, 1.0)
MARGIN_GRID = (0.0, 0.02, 0.05, 0.10)
EXPECTED_INPUTS = {
    "desis_2021.csv": "85ac21e38fb990a75714f90be0d2ced643275adf4e46570f326e765709c48ccc",
    "prisma_2021.csv": "0c6ef3dff0e5eff1c3e9ebb349494465d4459ee189c2aeb089af4e7622822647",
    "desis_prisma_2021_paper_reconciled.xml": "1453cf193438e59ad61d4cdde2eb4c089c1c28c843517585f7eb47c0f4e5aa46",
}


def now() -> str:
    return datetime.now(timezone.utc).isoformat()


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def write_json(path: Path, payload: Any) -> None:
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def file_manifest(root: Path) -> dict[str, str]:
    return {p.name: sha256(p) for p in sorted(root.iterdir()) if p.is_file()}


def stable_bucket(block_id: str) -> int:
    digest = hashlib.sha256((SEED_TEXT + block_id).encode("utf-8")).digest()
    return int.from_bytes(digest[:8], byteorder="big") % 10


@dataclass
class PairedData:
    loc_id: np.ndarray
    crop: np.ndarray
    lon: np.ndarray
    lat: np.ndarray
    z_prisma: np.ndarray
    y_desis: np.ndarray
    split: np.ndarray
    classes: np.ndarray
    desis_wavelength_nm: np.ndarray


def load_data(data_dir: Path) -> PairedData:
    for name, expected in EXPECTED_INPUTS.items():
        actual = sha256(data_dir / name)
        if actual != expected:
            raise RuntimeError(f"Input hash mismatch for {name}: {actual} != {expected}")
    desis = pd.read_csv(data_dir / "desis_2021.csv")
    prisma = pd.read_csv(data_dir / "prisma_2021.csv")
    required = ["loc_id", "crop_name", "crop_number", "longitude", "latitude"]
    if desis.shape[0] != 16581 or prisma.shape[0] != 16581 or any(c not in desis for c in required) or any(c not in prisma for c in required):
        raise RuntimeError("Unexpected paired-library table shape or metadata columns")
    if not np.array_equal(desis.loc_id.to_numpy(), prisma.loc_id.to_numpy()):
        raise RuntimeError("DESIS/PRISMA loc_id ordering is not identical")
    for column in ["crop_name", "crop_number", "longitude", "latitude"]:
        if not np.array_equal(desis[column].to_numpy(), prisma[column].to_numpy()):
            raise RuntimeError(f"Paired metadata mismatch: {column}")
    dcols = [c for c in desis.columns if c.startswith("d") and c[1:].isdigit()]
    pcols = [c for c in prisma.columns if c.startswith("p") and c[1:].isdigit()]
    dwave = np.asarray([float(c[1:]) for c in dcols], dtype=np.float64)
    pwave = np.asarray([float(c[1:]) for c in pcols], dtype=np.float64)
    keep = dwave >= pwave.min()
    if not keep.any() or dwave[keep].max() > pwave.max():
        raise RuntimeError("Common-VNIR wavelength construction failed")
    y = desis[dcols].to_numpy(dtype=np.float64)[:, keep]
    raw_p = prisma[pcols].to_numpy(dtype=np.float64)
    z = np.vstack([np.interp(dwave[keep], pwave, row) for row in raw_p])
    loc = desis.loc_id.to_numpy(dtype=np.int64)
    crop = desis.crop_name.to_numpy(dtype=str)
    lon = desis.longitude.to_numpy(dtype=np.float64)
    lat = desis.latitude.to_numpy(dtype=np.float64)
    block = np.asarray([f"{int(np.floor((x + 180.0) / .01))}:{int(np.floor((y_ + 90.0) / .01))}" for x, y_ in zip(lon, lat, strict=True)])
    bucket = np.asarray([stable_bucket(x) for x in block], dtype=np.int8)
    split = np.where(bucket <= 5, "development", np.where(bucket <= 7, "validation", "final"))
    classes = np.asarray(sorted(set(crop)), dtype=str)
    for part in ("development", "validation", "final"):
        counts = {c: int(((split == part) & (crop == c)).sum()) for c in classes}
        if part == "final" and min(counts.values()) < 20:
            raise RuntimeError(f"Final class support violates pre-registration: {counts}")
        if min(counts.values()) < 1:
            raise RuntimeError(f"Missing crop class in {part}: {counts}")
    return PairedData(loc, crop, lon, lat, z, y, split, classes, dwave[keep])


def indices(data: PairedData, part: str) -> np.ndarray:
    return np.flatnonzero(data.split == part)


def class_index(labels: np.ndarray, classes: np.ndarray) -> np.ndarray:
    lookup = {c: i for i, c in enumerate(classes)}
    return np.asarray([lookup[x] for x in labels], dtype=np.int64)


def fit_diagonal_affine(x: np.ndarray, y: np.ndarray, alpha: float, weights: np.ndarray | None = None) -> tuple[np.ndarray, np.ndarray]:
    if weights is None:
        weights = np.ones(x.shape[0], dtype=np.float64)
    weights = np.asarray(weights, dtype=np.float64)
    if (weights < 0).any() or weights.sum() <= 0:
        raise RuntimeError("Invalid regression weights")
    w = weights / weights.sum()
    xm = (w[:, None] * x).sum(axis=0)
    ym = (w[:, None] * y).sum(axis=0)
    xc = x - xm
    yc = y - ym
    cov = (w[:, None] * xc * yc).sum(axis=0)
    var = (w[:, None] * xc * xc).sum(axis=0)
    a = cov / (var + alpha)
    b = ym - a * xm
    return a, b


def apply_affine(x: np.ndarray, a: np.ndarray, b: np.ndarray) -> np.ndarray:
    return x * a[None, :] + b[None, :]


def fit_bundle(z: np.ndarray, y: np.ndarray, labels: np.ndarray, classes: np.ndarray, global_alpha: float, decoder_alpha: float, residual_alpha: float) -> dict[str, Any]:
    ga, gb = fit_diagonal_affine(z, y, global_alpha)
    tg = apply_affine(z, ga, gb)
    scaler = StandardScaler().fit(y)
    decoder = LogisticRegression(
        C=1.0 / decoder_alpha,
        class_weight="balanced",
        solver="lbfgs",
        max_iter=2000,
        random_state=20260812,
    ).fit(scaler.transform(y), labels)
    if not np.array_equal(decoder.classes_, classes):
        raise RuntimeError("Decoder class order differs from the fixed class order")
    posterior = decoder.predict_proba(scaler.transform(tg))
    residual = y - tg
    ras, rbs = [], []
    for c in range(len(classes)):
        a, b = fit_diagonal_affine(z, residual, residual_alpha, posterior[:, c])
        ras.append(a)
        rbs.append(b)
    return {"global_a": ga, "global_b": gb, "residual_a": np.stack(ras), "residual_b": np.stack(rbs), "scaler": scaler, "decoder": decoder, "classes": classes, "config": {"global_alpha": global_alpha, "decoder_alpha": decoder_alpha, "residual_alpha": residual_alpha}}


def logits(bundle: dict[str, Any], x: np.ndarray) -> np.ndarray:
    return np.asarray(bundle["decoder"].decision_function(bundle["scaler"].transform(x)), dtype=np.float64)


def top_and_margin(score: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    order = np.argsort(score, axis=1)
    top = order[:, -1]
    margin = score[np.arange(score.shape[0]), order[:, -1]] - score[np.arange(score.shape[0]), order[:, -2]]
    return top, margin


def transports(bundle: dict[str, Any], z: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    global_x = apply_affine(z, bundle["global_a"], bundle["global_b"])
    proba = bundle["decoder"].predict_proba(bundle["scaler"].transform(global_x))
    residual = z[:, None, :] * bundle["residual_a"][None, :, :] + bundle["residual_b"][None, :, :]
    semantic_x = global_x + np.einsum("nc,ncd->nd", proba, residual)
    sg, mg = top_and_margin(logits(bundle, global_x))
    ss, ms = top_and_margin(logits(bundle, semantic_x))
    return global_x, semantic_x, sg, mg, ms


def metrics(pred: np.ndarray, label: np.ndarray, x: np.ndarray, y: np.ndarray, classes: np.ndarray) -> dict[str, Any]:
    per_rmse = np.sqrt(np.mean((x - y) ** 2, axis=1))
    denom = np.linalg.norm(x, axis=1) * np.linalg.norm(y, axis=1)
    cos = np.divide(np.sum(x * y, axis=1), denom, out=np.ones_like(denom), where=denom > 0)
    sam = np.arccos(np.clip(cos, -1.0, 1.0))
    return {
        "accuracy": float(accuracy_score(label, pred)),
        "macro_f1": float(f1_score(label, pred, labels=classes, average="macro", zero_division=0)),
        "per_class_f1": {str(c): float(v) for c, v in zip(classes, f1_score(label, pred, labels=classes, average=None, zero_division=0), strict=True)},
        "rmse": float(per_rmse.mean()),
        "sam_rad": float(sam.mean()),
        "per_sample_rmse": per_rmse,
        "per_sample_sam": sam,
    }


def split_manifest(data: PairedData) -> dict[str, Any]:
    counts = {part: {str(c): int(((data.split == part) & (data.crop == c)).sum()) for c in data.classes} for part in ("development", "validation", "final")}
    ids = {part: [int(x) for x in data.loc_id[indices(data, part)]] for part in ("development", "validation", "final")}
    return {
        "schema": "smst-r4-split-v1",
        "seed_text": SEED_TEXT,
        "spatial_block_rule": "floor((longitude+180)/0.01):floor((latitude+90)/0.01)",
        "bucket_rule": "SHA-256(seed_text + block_id) mod 10; 0-5 development, 6-7 validation, 8-9 final",
        "counts": counts,
        "loc_id_list_sha256": {part: hashlib.sha256("\n".join(map(str, sorted(values))).encode()).hexdigest() for part, values in ids.items()},
        "wavelength_nm": [float(v) for v in data.desis_wavelength_nm],
    }


def prepare_output(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=False)


def stage_development(data: PairedData, output: Path, prereg: Path, script: Path, data_dir: Path) -> None:
    prepare_output(output)
    dev = indices(data, "development")
    state: dict[str, Any] = {}
    for ga in GLOBAL_GRID:
        for da in DECODER_GRID:
            for ra in RESIDUAL_GRID:
                key = f"g={ga:.0e}|d={da:.0e}|r={ra:.0e}"
                state[key] = fit_bundle(data.z_prisma[dev], data.y_desis[dev], data.crop[dev], data.classes, ga, da, ra)
    with (output / "development_models.pkl").open("wb") as handle:
        pickle.dump(state, handle, protocol=pickle.HIGHEST_PROTOCOL)
    manifest = {
        "schema": "smst-r4-development-v1",
        "created_at": now(),
        "pre_registration_sha256": sha256(prereg),
        "script_sha256": sha256(script),
        "input_sha256": {name: sha256(data_dir / name) for name in EXPECTED_INPUTS},
        "split": split_manifest(data),
        "development_row_count": int(dev.size),
        "model_count": len(state),
        "final_evaluation_opened": False,
    }
    write_json(output / "DEVELOPMENT_MANIFEST.json", manifest)
    (output / "SHA256SUMS").write_text("\n".join(f"{digest}  {name}" for name, digest in file_manifest(output).items()) + "\n", encoding="utf-8")


def stage_validation(data: PairedData, development: Path, output: Path, prereg: Path, script: Path) -> None:
    prepare_output(output)
    manifest = json.loads((development / "DEVELOPMENT_MANIFEST.json").read_text(encoding="utf-8"))
    if manifest["pre_registration_sha256"] != sha256(prereg) or manifest["script_sha256"] != sha256(script):
        raise RuntimeError("Development state is not bound to the current preregistration/script")
    with (development / "development_models.pkl").open("rb") as handle:
        models = pickle.load(handle)
    val = indices(data, "validation")
    rows: list[dict[str, Any]] = []
    best: tuple[Any, ...] | None = None
    selected: dict[str, Any] | None = None
    for key, bundle in models.items():
        global_x, semantic_x, pred_global, margin_global, margin_semantic = transports(bundle, data.z_prisma[val])
        pred_semantic_idx, _ = top_and_margin(logits(bundle, semantic_x))
        pred_global_label = data.classes[pred_global]
        pred_semantic_label = data.classes[pred_semantic_idx]
        for margin in MARGIN_GRID:
            accepted = (pred_semantic_idx == pred_global) & (margin_semantic >= margin_global + margin)
            chosen = np.where(accepted[:, None], semantic_x, global_x)
            # By construction, committed labels are exactly the global decoder labels.
            score = metrics(pred_global_label, data.crop[val], chosen, data.y_desis[val], data.classes)
            row = {"model_key": key, "margin": margin, "coverage": float(accepted.mean()), "macro_f1": score["macro_f1"], "rmse": score["rmse"], "sam_rad": score["sam_rad"], "semantic_label_change_rate_before_gate": float((pred_semantic_label != pred_global_label).mean())}
            rows.append(row)
            cfg = bundle["config"]
            rank = (-row["macro_f1"], row["rmse"], -row["coverage"], cfg["global_alpha"], cfg["decoder_alpha"], cfg["residual_alpha"], margin)
            if best is None or rank < best:
                best, selected = rank, {"model_key": key, "margin": margin, "config": cfg, "validation_row": row}
    if selected is None:
        raise RuntimeError("No validation model was selected")
    with (output / "validation_grid.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader(); writer.writerows(rows)
    decision = {
        "schema": "smst-r4-final-decision-v1",
        "created_at": now(),
        "pre_registration_sha256": sha256(prereg),
        "script_sha256": sha256(script),
        "development_models_sha256": sha256(development / "development_models.pkl"),
        "development_manifest_sha256": sha256(development / "DEVELOPMENT_MANIFEST.json"),
        "selected": selected,
        "final_evaluation_opened": False,
    }
    write_json(output / "FINAL_DECISION_LOCK.json", decision)
    report = ["# SMST-R4 validation selection", "", f"Selected `{selected['model_key']}` at margin {selected['margin']:.2f}.", f"Validation macro-F1: {selected['validation_row']['macro_f1']:.6f}; RMSE: {selected['validation_row']['rmse']:.6f}; coverage: {selected['validation_row']['coverage']:.6f}.", "", "The final partition was not evaluated in this stage."]
    (output / "VALIDATION_REPORT.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    (output / "SHA256SUMS").write_text("\n".join(f"{digest}  {name}" for name, digest in file_manifest(output).items()) + "\n", encoding="utf-8")


def stage_final(data: PairedData, development: Path, validation: Path, output: Path, prereg: Path, script: Path) -> None:
    prepare_output(output)
    decision = json.loads((validation / "FINAL_DECISION_LOCK.json").read_text(encoding="utf-8"))
    if decision["pre_registration_sha256"] != sha256(prereg) or decision["script_sha256"] != sha256(script):
        raise RuntimeError("Final decision lock is not bound to the current preregistration/script")
    if decision["development_models_sha256"] != sha256(development / "development_models.pkl"):
        raise RuntimeError("Development models do not match the final decision lock")
    with (development / "development_models.pkl").open("rb") as handle:
        models = pickle.load(handle)
    selected = decision["selected"]
    bundle = models[selected["model_key"]]
    final = indices(data, "final")
    z, y, label = data.z_prisma[final], data.y_desis[final], data.crop[final]
    global_x, semantic_x, global_idx, margin_global, margin_semantic = transports(bundle, z)
    semantic_idx, _ = top_and_margin(logits(bundle, semantic_x))
    accepted = (semantic_idx == global_idx) & (margin_semantic >= margin_global + float(selected["margin"]))
    smst_x = np.where(accepted[:, None], semantic_x, global_x)
    identity_idx, _ = top_and_margin(logits(bundle, z))
    pred_global = data.classes[global_idx]
    pred_semantic = data.classes[semantic_idx]
    pred_identity = data.classes[identity_idx]
    # Diagnostic oracle: true crop class weights residual maps but is never a deployed rule.
    label_idx = class_index(label, data.classes)
    residual = z * bundle["residual_a"][label_idx] + bundle["residual_b"][label_idx]
    oracle_x = global_x + residual
    oracle_idx, _ = top_and_margin(logits(bundle, oracle_x))
    result_metrics = {
        "identity": metrics(pred_identity, label, z, y, data.classes),
        "global_ridge": metrics(pred_global, label, global_x, y, data.classes),
        "unconstrained_semantic": metrics(pred_semantic, label, semantic_x, y, data.classes),
        "smst": metrics(pred_global, label, smst_x, y, data.classes),
        "label_conditioned_oracle_diagnostic": metrics(data.classes[oracle_idx], label, oracle_x, y, data.classes),
    }
    global_rmse = result_metrics["global_ridge"].pop("per_sample_rmse")
    global_sam = result_metrics["global_ridge"].pop("per_sample_sam")
    for name, values in result_metrics.items():
        if "per_sample_rmse" in values: values.pop("per_sample_rmse")
        if "per_sample_sam" in values: values.pop("per_sample_sam")
    smst_per_rmse = np.sqrt(np.mean((smst_x - y) ** 2, axis=1))
    pred_smst = pred_global  # accepted rows preserve the global top label; rejected rows use global.
    correct_to_incorrect = (pred_global == label) & (pred_smst != label)
    spectral_harm = (smst_per_rmse - global_rmse > 0.25) & ((smst_per_rmse - global_rmse) / np.maximum(global_rmse, 1e-12) > 0.05)
    union_harm = correct_to_incorrect | spectral_harm
    paired = {
        "coverage": float(accepted.mean()),
        "semantic_label_changes_before_gate": int((pred_semantic != pred_global).sum()),
        "semantic_label_changes_after_gate": int((pred_global != pred_global).sum()),
        "correct_to_incorrect_vs_global": int(correct_to_incorrect.sum()),
        "spectral_harms_vs_global": int(spectral_harm.sum()),
        "component_union_harms_vs_global": int(union_harm.sum()),
        "smst_minus_global_rmse": float(result_metrics["smst"]["rmse"] - result_metrics["global_ridge"]["rmse"]),
        "smst_minus_global_sam_rad": float(result_metrics["smst"]["sam_rad"] - result_metrics["global_ridge"]["sam_rad"]),
        "smst_minus_global_macro_f1": float(result_metrics["smst"]["macro_f1"] - result_metrics["global_ridge"]["macro_f1"]),
    }
    with (output / "final_per_location.csv").open("w", newline="", encoding="utf-8") as handle:
        cols = ["loc_id", "crop_label", "identity_prediction", "global_prediction", "semantic_prediction", "smst_committed_semantic", "global_margin", "semantic_margin", "global_rmse", "smst_rmse", "spectral_harm_vs_global", "union_harm_vs_global"]
        writer = csv.DictWriter(handle, fieldnames=cols); writer.writeheader()
        for i in range(final.size):
            writer.writerow({"loc_id": int(data.loc_id[final[i]]), "crop_label": label[i], "identity_prediction": pred_identity[i], "global_prediction": pred_global[i], "semantic_prediction": pred_semantic[i], "smst_committed_semantic": bool(accepted[i]), "global_margin": float(margin_global[i]), "semantic_margin": float(margin_semantic[i]), "global_rmse": float(global_rmse[i]), "smst_rmse": float(smst_per_rmse[i]), "spectral_harm_vs_global": bool(spectral_harm[i]), "union_harm_vs_global": bool(union_harm[i])})
    summary = {"schema": "smst-r4-final-results-v1", "created_at": now(), "pre_registration_sha256": sha256(prereg), "script_sha256": sha256(script), "decision_lock_sha256": sha256(validation / "FINAL_DECISION_LOCK.json"), "selected": selected, "final_row_count": int(final.size), "metrics": result_metrics, "paired_vs_global": paired, "claim_boundary": "Paired evaluation on one August-2021 agricultural overlap. Top-label preservation is exact only with respect to the frozen decoder and global-ridge fallback; it is not a population safety certificate."}
    write_json(output / "FINAL_SUMMARY.json", summary)
    report = ["# SMST-R4 final result", "", f"Final cases: {final.size}", f"SMST coverage: {paired['coverage']:.6f}", f"SMST - global RMSE: {paired['smst_minus_global_rmse']:.6f}", f"SMST - global macro-F1: {paired['smst_minus_global_macro_f1']:.6f}", f"Component-union harms versus global: {paired['component_union_harms_vs_global']}", "", "Scope: one paired DESIS/PRISMA agricultural overlap; no population or universal-safety claim."]
    (output / "FINAL_REPORT.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    (output / "SHA256SUMS").write_text("\n".join(f"{digest}  {name}" for name, digest in file_manifest(output).items()) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("stage", choices=("development", "validation", "final"))
    parser.add_argument("--data-dir", required=True, type=Path)
    parser.add_argument("--prereg", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--development", type=Path)
    parser.add_argument("--validation", type=Path)
    args = parser.parse_args()
    data = load_data(args.data_dir.resolve())
    if args.stage == "development":
        stage_development(data, args.output.resolve(), args.prereg.resolve(), Path(__file__).resolve(), args.data_dir.resolve())
    elif args.stage == "validation":
        if args.development is None:
            raise SystemExit("--development is required for validation")
        stage_validation(data, args.development.resolve(), args.output.resolve(), args.prereg.resolve(), Path(__file__).resolve())
    else:
        if args.development is None or args.validation is None:
            raise SystemExit("--development and --validation are required for final")
        stage_final(data, args.development.resolve(), args.validation.resolve(), args.output.resolve(), args.prereg.resolve(), Path(__file__).resolve())


if __name__ == "__main__":
    main()
